#!/bin/bash
# Real-STT voice-capture E2E audio setup for headless/CI environments.
#
# Stratum records via cpal (ALSA backend). On machines where the default
# input device is a physical HDA card that has no PipeWire/Pulse route
# (headless Xvfb, CI containers), cpal's hw stream fails with:
#   "get_htstamp `0.0` was earlier than get_trigger_htstamp ..."
# and delivers ZERO samples (FLAC files are 42-byte headers).
#
# This script generates an ALSA config that routes `pcm.default` to the ALSA
# `null` plugin, which keeps the stream healthy and produces real (silent)
# sample data. It is NOT a product change — it only fixes the test
# environment. Start tauri-driver / the app with:
#   ALSA_CONFIG_PATH="$PWD/e2e/alsa-null.conf"
#
# Alternative (real capture from a physical mic with a healthy route):
#   pcm.default -> plug(hw:1,0)  (see /tmp/asound-voice.conf history)
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
CONF="$DIR/alsa-null.conf"
cat > "$CONF" <<'EOF'
# Headless-safe ALSA config: route default capture to the null plugin so
# cpal streams stay alive and yield real (silent) samples. Generated by
# e2e/alsa-null-setup.sh — do not hand-edit.
pcm.!default {
    type null
}
ctl.!default {
    type hw
    card 1
}
EOF
echo "Wrote $CONF"
echo "Run with: ALSA_CONFIG_PATH=$CONF"
