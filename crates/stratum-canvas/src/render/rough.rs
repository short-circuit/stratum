//! Rough (hand-drawn) geometry generation for Excalidraw elements.
//!
//! This module ports Excalidraw's `generateRoughOptions` (the shipped
//! `rt` function in the Excalidraw bundle) to `roughr`, the Rust port of
//! rough.js. The option mapping, seed handling, dash patterns, fill styles,
//! roughness clamping and vertex preservation all follow that function so a
//! Stratum render matches the React whiteboard.
//!
//! [`element_paths`] returns world-coordinate [`ScenePath`]s for one element.
//! Text, images and frames have no rough geometry (glyphs, image nodes and
//! frame outlines are drawn by the SVG/raster writers). Freedraw strokes are
//! emitted as straight segments with round caps via [`freedraw_path`], and
//! arrowheads are generated by [`arrowhead_paths`] (re-exported from
//! `rough_arrow.rs`).
//!
//! Colour strings in the returned paths are the element's original colours;
//! theme adaptation happens in the scene builder. `roughr` receives the
//! opacity-multiplied alpha because it has no separate opacity knob.
//!
//! Paths are built directly from `roughr`'s [`Drawable`]/`OpSet`/`Op` data
//! rather than from its `d` strings: `ops_to_path` serialises every `Move` as
//! `L`, which would join the strokes of a multi-stroke sketch with chords.

use pkm_core::{PkmError, PkmResult};
use roughr::core::{
    Drawable, FillStyle as RoughFillStyle, Op, OpSetType, OpType, Options, OptionsBuilder,
};
use roughr::generator::Generator;
use roughr::{Point2D, Srgba};

use crate::element::Element;
use crate::element_kind::{ElementKind, FillStyle, StrokeStyle};
use crate::geometry::Point;
use crate::render::color::{is_transparent, parse_color, to_srgba};
use crate::render::rounded::{
    diamond_points, element_affine, is_loop, polyline, rounded_diamond_path, rounded_rect_path,
};
use crate::render::scene::ScenePath;
use crate::render::svg_path::{PathData, PathOp};

pub use crate::render::rough_arrow::arrowhead_paths;

/// Excalidraw "cartoonist" roughness preset; below it vertices are preserved.
const CARTOONIST_ROUGHNESS: f64 = 2.0;

/// Rough options plus the colour metadata needed to classify generated paths.
pub(crate) struct Sketch {
    /// roughr options.
    pub(crate) options: Options,
    /// Stroke colour string, when the element strokes.
    pub(crate) stroke_color: Option<String>,
    /// Fill colour string, when the element fills.
    pub(crate) fill_color: Option<String>,
    /// Outline stroke width.
    pub(crate) stroke_width: f64,
    /// Outline dash pattern.
    pub(crate) dash: Option<Vec<f64>>,
    /// Element opacity in `0.0..=1.0`.
    pub(crate) opacity: f64,
}

/// Build rough paths for one element in world coordinates.
///
/// # Errors
///
/// Returns [`PkmError::Canvas`] when roughr cannot build its options.
pub fn element_paths(element: &Element) -> PkmResult<Vec<ScenePath>> {
    let kind = element.kind();
    let sketch = sketch_options(element, false)?;
    match kind {
        ElementKind::Text | ElementKind::Image | ElementKind::Frame | ElementKind::MagicFrame => {
            Ok(Vec::new())
        }
        ElementKind::Freedraw => Ok(vec![freedraw_element(element, &sketch)]),
        _ => {
            let generator = Generator::default();
            let drawable = match kind {
                ElementKind::Rectangle | ElementKind::Embeddable | ElementKind::Iframe => {
                    if element.style().roundness.is_some() {
                        generator.path(rounded_rect_path(element), &Some(sketch.options.clone()))
                    } else {
                        generator.rectangle(
                            0.0_f32,
                            0.0_f32,
                            element.width() as f32,
                            element.height() as f32,
                            &Some(sketch.options.clone()),
                        )
                    }
                }
                ElementKind::Diamond => {
                    if element.style().roundness.is_some() {
                        generator.path(rounded_diamond_path(element), &Some(sketch.options.clone()))
                    } else {
                        generator.polygon(
                            &rough_points(&diamond_points(element)),
                            &Some(sketch.options.clone()),
                        )
                    }
                }
                ElementKind::Ellipse => generator.ellipse(
                    (element.width() / 2.0) as f32,
                    (element.height() / 2.0) as f32,
                    element.width() as f32,
                    element.height() as f32,
                    &Some(sketch.options.clone()),
                ),
                ElementKind::Line | ElementKind::Arrow => {
                    let points = rough_points(&polyline(element));
                    if sketch.fill_color.is_some() {
                        generator.polygon(&points, &Some(sketch.options.clone()))
                    } else if element.style().roundness.is_some() {
                        generator.curve(&points, &Some(sketch.options.clone()))
                    } else {
                        generator.linear_path(&points, false, &Some(sketch.options.clone()))
                    }
                }
                // Unknown kinds are preserved by the model; draw them as a
                // plain rectangle outline so they stay visible.
                _ => generator.rectangle(
                    0.0_f32,
                    0.0_f32,
                    element.width() as f32,
                    element.height() as f32,
                    &Some(sketch.options.clone()),
                ),
            };
            Ok(drawable_paths(element, &sketch, &drawable))
        }
    }
}

/// Convert model points into roughr's `f32` point type.
///
/// roughr's generators are generic over the coordinate type; the renderer uses
/// `f32` because that is the type the option set and `Drawable` operations are
/// documented around. The world coordinates are widened back to `f64` when the
/// ops are mapped to [`PathOp`].
fn rough_points(points: &[Point2D<f64>]) -> Vec<Point2D<f32>> {
    points
        .iter()
        .map(|point| Point2D::new(point.x as f32, point.y as f32))
        .collect()
}

/// Rough paths for a freedraw polyline (no roughening: straight segments,
/// round caps).
///
/// The returned path has an empty `element_id`; [`element_paths`] fills it in
/// for element-owned strokes. Renderers should draw the stroke with round line
/// caps and joins.
pub fn freedraw_path(points: &[Point], stroke: &str, width: f64) -> ScenePath {
    let mut ops = Vec::with_capacity(points.len());
    for (index, point) in points.iter().enumerate() {
        if index == 0 {
            ops.push(crate::render::svg_path::PathOp::MoveTo(*point));
        } else {
            ops.push(crate::render::svg_path::PathOp::LineTo(*point));
        }
    }
    ScenePath {
        element_id: String::new(),
        ops,
        fill: None,
        stroke: if is_transparent(stroke) {
            None
        } else {
            Some(stroke.to_string())
        },
        stroke_width: width,
        dash: None,
        opacity: 1.0,
        clip: None,
    }
}

/// Freedraw element path in world coordinates.
fn freedraw_element(element: &Element, sketch: &Sketch) -> ScenePath {
    let points: Vec<Point> = polyline(element)
        .iter()
        .map(|point| Point::new(point.x, point.y))
        .collect();
    let stroke = sketch.stroke_color.clone().unwrap_or_default();
    let mut path = freedraw_path(&points, &stroke, sketch.stroke_width);
    path.element_id = element.id().to_string();
    path.dash = sketch.dash.clone();
    path.opacity = sketch.opacity;
    let affine = element_affine(element);
    path.ops = PathData { ops: path.ops }.transformed(&affine).ops;
    path
}

/// Build the Excalidraw rough options for one element.
///
/// `explicit` mirrors Excalidraw's `preserveVertices` argument, which is set
/// for rounded rectangles/diamonds and elbow arrows.
pub(crate) fn sketch_options(element: &Element, explicit: bool) -> PkmResult<Sketch> {
    let style = element.style();
    let kind = element.kind();
    let stroke_width = if style.stroke_style == StrokeStyle::Solid {
        style.stroke_width
    } else {
        style.stroke_width + 0.5
    };
    let dash = match style.stroke_style {
        StrokeStyle::Dashed => Some(vec![8.0, 8.0 + style.stroke_width]),
        StrokeStyle::Dotted => Some(vec![1.5, 6.0 + style.stroke_width]),
        StrokeStyle::Solid => None,
    };
    let stroke_rgba = parse_color(&style.stroke_color);
    let fill_allowed = match kind {
        ElementKind::Arrow => false,
        ElementKind::Line | ElementKind::Freedraw => is_loop(&polyline(element)),
        _ => true,
    };
    let fill_rgba = if fill_allowed {
        parse_color(&style.background_color)
    } else {
        None
    };
    let opacity = (style.opacity / 100.0).clamp(0.0, 1.0);

    let mut builder = OptionsBuilder::default();
    builder
        .seed(style.seed)
        .stroke_width(stroke_width as f32)
        .fill_weight((style.stroke_width / 2.0) as f32)
        .hachure_gap((style.stroke_width * 4.0) as f32)
        .hachure_angle(-41.0_f32)
        .roughness(roughness_for(element) as f32)
        .disable_multi_stroke(style.stroke_style != StrokeStyle::Solid)
        .preserve_vertices(explicit || style.roughness < CARTOONIST_ROUGHNESS);
    if kind == ElementKind::Ellipse {
        builder.curve_fitting(1.0_f32);
    }
    if let Some(dash) = &dash {
        builder.stroke_line_dash(dash.clone());
    }
    if let Some(rgba) = stroke_rgba {
        builder.stroke(to_srgba(rgba, style.opacity));
    } else {
        builder.stroke(tos_transparent());
    }
    if let Some(rgba) = fill_rgba {
        builder.fill(to_srgba(rgba, style.opacity));
        builder.fill_style(rough_fill_style(style.fill_style));
    }
    let options = builder
        .build()
        .map_err(|e| PkmError::Canvas(format!("rough options: {e}")))?;

    Ok(Sketch {
        options,
        stroke_color: if is_transparent(&style.stroke_color) {
            None
        } else {
            Some(style.stroke_color.clone())
        },
        fill_color: if fill_rgba.is_some() {
            Some(style.background_color.clone())
        } else {
            None
        },
        stroke_width,
        dash,
        opacity,
    })
}

/// A fully transparent roughr colour (used when an element has no stroke).
fn tos_transparent() -> Srgba {
    Srgba::new(0.0, 0.0, 0.0, 0.0)
}

/// Map the Excalidraw fill style to roughr's.
fn rough_fill_style(fill: FillStyle) -> RoughFillStyle {
    match fill {
        FillStyle::Hachure => RoughFillStyle::Hachure,
        FillStyle::CrossHatch => RoughFillStyle::CrossHatch,
        FillStyle::Solid => RoughFillStyle::Solid,
        FillStyle::ZigZag => RoughFillStyle::ZigZag,
        FillStyle::Dots => RoughFillStyle::Dots,
    }
}

/// Excalidraw's roughness clamp (`Vm` in the shipped bundle).
///
/// The second clause is Excalidraw's `isRoughnessScaled` type set
/// (rectangle/iframe/embeddable/line/diamond/image) combined with a present
/// `roundness`; the third clause is the linear-element clause. The spec
/// shorthand calls both "linear"; this follows the shipped bundle.
pub(crate) fn roughness_for(element: &Element) -> f64 {
    let roughness = element.style().roughness;
    let max_size = element.width().max(element.height());
    let min_size = element.width().min(element.height());
    let scaled_kind = matches!(
        element.kind(),
        ElementKind::Rectangle
            | ElementKind::Iframe
            | ElementKind::Embeddable
            | ElementKind::Line
            | ElementKind::Diamond
            | ElementKind::Image
    );
    let large = (min_size >= 20.0 && max_size >= 50.0)
        || (min_size >= 15.0 && element.style().roundness.is_some() && scaled_kind)
        || (element.kind().is_linear() && max_size >= 50.0);
    if large {
        roughness
    } else {
        let divisor = if max_size < 10.0 { 3.0 } else { 2.0 };
        (roughness / divisor).min(2.5)
    }
}

/// Convert a roughr drawable into scene paths without going through the lossy
/// `ops_to_path` serialiser (it emits `Move` as `L`, which adds chords between
/// the strokes of a multi-stroke sketch).
///
/// Each [`OpSetType`] maps to one scene path: `Path` becomes a stroke with the
/// element's stroke colour, `FillPath` becomes a fill and `FillSketch` becomes
/// a fill-coloured stroke at the fill weight. Every [`OpType::Move`] starts a
/// new sub-path; it never becomes a line-to, so consecutive strokes stay
/// disconnected instead of being joined by a chord. The element affine is
/// applied to the finished ops.
pub(crate) fn drawable_paths(
    element: &Element,
    colors: &Sketch,
    drawable: &Drawable<f32>,
) -> Vec<ScenePath> {
    let affine = element_affine(element);
    let fill_weight = (element.style().stroke_width / 2.0) as f32;
    let mut out = Vec::with_capacity(drawable.sets.len());
    for set in &drawable.sets {
        let ops = path_ops(&set.ops);
        if ops.is_empty() {
            continue;
        }
        let ops = PathData { ops }.transformed(&affine).ops;
        match set.op_set_type {
            OpSetType::FillPath => out.push(ScenePath {
                element_id: element.id().to_string(),
                ops,
                fill: colors.fill_color.clone(),
                stroke: None,
                stroke_width: 0.0,
                dash: None,
                opacity: colors.opacity,
                clip: None,
            }),
            OpSetType::FillSketch => out.push(ScenePath {
                element_id: element.id().to_string(),
                ops,
                fill: None,
                stroke: colors.fill_color.clone(),
                stroke_width: f64::from(fill_weight),
                dash: None,
                opacity: colors.opacity,
                clip: None,
            }),
            OpSetType::Path => out.push(ScenePath {
                element_id: element.id().to_string(),
                ops,
                fill: None,
                stroke: colors.stroke_color.clone(),
                stroke_width: colors.stroke_width,
                dash: colors.dash.clone(),
                opacity: colors.opacity,
                clip: None,
            }),
        }
    }
    out
}

/// Map roughr ops to structural path ops.
///
/// `Move` becomes [`PathOp::MoveTo`] (a new sub-path), `LineTo` becomes
/// [`PathOp::LineTo`] and `BCurveTo` becomes [`PathOp::CurveTo`]. Ops with the
/// wrong number of coordinates are skipped rather than failing the whole
/// element.
fn path_ops(ops: &[Op<f32>]) -> Vec<PathOp> {
    let mut out = Vec::with_capacity(ops.len());
    for op in ops {
        let data = &op.data;
        match &op.op {
            OpType::Move if data.len() >= 2 => {
                out.push(PathOp::MoveTo(Point::new(
                    f64::from(data[0]),
                    f64::from(data[1]),
                )));
            }
            OpType::LineTo if data.len() >= 2 => {
                out.push(PathOp::LineTo(Point::new(
                    f64::from(data[0]),
                    f64::from(data[1]),
                )));
            }
            OpType::BCurveTo if data.len() >= 6 => {
                out.push(PathOp::CurveTo {
                    c1: Point::new(f64::from(data[0]), f64::from(data[1])),
                    c2: Point::new(f64::from(data[2]), f64::from(data[3])),
                    to: Point::new(f64::from(data[4]), f64::from(data[5])),
                });
            }
            _ => {}
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::element::Style;
    use crate::element_kind::FillStyle;

    #[test]
    fn rectangle_paths_are_world_positioned() {
        let mut rect = Element::new(ElementKind::Rectangle, "r", 10.0, 20.0, 100.0, 60.0);
        rect.set_style(&Style {
            background_color: "#a5d8ff".to_string(),
            fill_style: FillStyle::Solid,
            ..Style::default()
        });
        let paths = element_paths(&rect).unwrap();
        assert!(!paths.is_empty());
        assert!(paths
            .iter()
            .any(|path| path.fill.as_deref() == Some("#a5d8ff")));
        let bounds = crate::render::scene::path_bounds(&paths[0].ops);
        assert!(bounds.x >= 10.0 - 5.0);
        assert!(bounds.right() >= 100.0);
    }

    #[test]
    fn text_and_frames_have_no_rough_paths() {
        let text = Element::new(ElementKind::Text, "t", 0.0, 0.0, 10.0, 10.0);
        assert!(element_paths(&text).unwrap().is_empty());
        let frame = Element::new(ElementKind::Frame, "f", 0.0, 0.0, 10.0, 10.0);
        assert!(element_paths(&frame).unwrap().is_empty());
    }

    #[test]
    fn roughness_is_clamped_for_small_elements() {
        let mut rect = Element::new(ElementKind::Rectangle, "r", 0.0, 0.0, 8.0, 8.0);
        rect.set_style(&Style {
            roughness: 3.0,
            ..Style::default()
        });
        assert!((roughness_for(&rect) - 1.0).abs() < 1e-9);
        let mut large = Element::new(ElementKind::Rectangle, "l", 0.0, 0.0, 100.0, 100.0);
        large.set_style(&Style {
            roughness: 3.0,
            ..Style::default()
        });
        assert!((roughness_for(&large) - 3.0).abs() < 1e-9);
    }

    #[test]
    fn freedraw_is_straight_segments() {
        let path = freedraw_path(
            &[Point::new(0.0, 0.0), Point::new(10.0, 5.0)],
            "#1e1e1e",
            2.0,
        );
        assert_eq!(path.ops.len(), 2);
        assert!(matches!(
            path.ops[0],
            crate::render::svg_path::PathOp::MoveTo(_)
        ));
        assert_eq!(path.stroke.as_deref(), Some("#1e1e1e"));
    }
}
