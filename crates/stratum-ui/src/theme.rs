//! Theme derivation ported 1:1 from the shipped web application.
//!
//! `src/lib/theme.ts` derives a ten-step shade ladder for the primary and
//! secondary colours, and `src/lib/muiTheme.ts` turns the secondary hue into
//! background, divider and text tokens. This module reproduces those formulas
//! exactly, including JavaScript `Math.round` semantics for non-negative
//! channels, so the gpui shell and the frozen React shell render the same
//! palette for the same configuration.
//!
//! The derived palette is then mapped onto gpui-kit's semantic tokens by
//! [`apply_to_kit`]. The golden values in the unit tests were generated by
//! running the real TypeScript through node; changing a formula here without
//! changing the shipped formula is a parity regression.

use std::collections::BTreeMap;

use gpui_kit::component::{Theme, ThemeMode};
use gpui_kit::*;

/// An HSL colour with integer channels, matching the JavaScript derivation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Hsl {
    /// Hue in degrees.
    pub h: i32,
    /// Saturation percentage.
    pub s: i32,
    /// Lightness percentage.
    pub l: i32,
}

/// Shade ladder used by the shipped theme: `(step, base_lightness)`.
pub const SHADE_STEPS: [(u16, i32); 10] = [
    (50, 96),
    (100, 92),
    (200, 84),
    (300, 68),
    (400, 55),
    (500, 50),
    (600, 42),
    (700, 34),
    (800, 26),
    (900, 16),
];

/// Convert a hex colour to HSL exactly like the shipped `hexToHsl`.
///
/// Three-digit shorthand is expanded; invalid input falls back to
/// `Hsl { h: 0, s: 0, l: 0 }` because the JavaScript parser leaves the
/// channels at zero when the string matches neither the three- nor six-digit
/// shape. (`parseInt` returning `NaN` for malformed six-digit input is treated
/// as zero here so the port stays total.)
pub fn hex_to_hsl(hex: &str) -> Hsl {
    let clean = hex.trim_start_matches('#');
    let (mut r, mut g, mut b) = (0.0_f64, 0.0_f64, 0.0_f64);
    if clean.len() == 3 {
        r = parse_channel(&clean[0..1]);
        g = parse_channel(&clean[1..2]);
        b = parse_channel(&clean[2..3]);
    } else if clean.len() == 6 {
        r = parse_channel(&clean[0..2]);
        g = parse_channel(&clean[2..4]);
        b = parse_channel(&clean[4..6]);
    }
    // The shipped code divides by 255 even for the fallback path, where all
    // channels are zero.
    r /= 255.0;
    g /= 255.0;
    b /= 255.0;

    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    let l = (max + min) / 2.0;
    let mut h = 0.0_f64;
    let mut s = 0.0_f64;
    if max != min {
        let d = max - min;
        s = if l > 0.5 {
            d / (2.0 - max - min)
        } else {
            d / (max + min)
        };
        if max == r {
            h = ((g - b) / d + if g < b { 6.0 } else { 0.0 }) / 6.0;
        } else if max == g {
            h = ((b - r) / d + 2.0) / 6.0;
        } else if max == b {
            h = ((r - g) / d + 4.0) / 6.0;
        }
    }
    Hsl {
        h: js_round(h * 360.0),
        s: js_round(s * 100.0),
        l: js_round(l * 100.0),
    }
}

/// Parse one or two hex digits into a 0..255 channel, or zero when invalid.
fn parse_channel(digits: &str) -> f64 {
    let expanded = if digits.len() == 1 {
        format!("{digits}{digits}")
    } else {
        digits.to_string()
    };
    u8::from_str_radix(&expanded, 16)
        .map(f64::from)
        .unwrap_or(0.0)
}

/// JavaScript `Math.round` for the non-negative values produced by the port.
fn js_round(value: f64) -> i32 {
    (value + 0.5).floor() as i32
}

/// Offset applied to the shade ladder for a given input lightness.
pub fn shade_offset(input_l: i32) -> i32 {
    input_l - 50
}

/// Derive the ten-step shade ladder for `hex`, clamped to `0..=100`.
pub fn derive_shades(hex: &str) -> BTreeMap<u16, Hsl> {
    let base = hex_to_hsl(hex);
    let offset = shade_offset(base.l);
    let mut shades = BTreeMap::new();
    for (step, lightness) in SHADE_STEPS {
        let adjusted = (lightness + offset).clamp(0, 100);
        shades.insert(
            step,
            Hsl {
                h: base.h,
                s: base.s,
                l: adjusted,
            },
        );
    }
    shades
}

/// Format an HSL colour the way the shipped CSS custom properties do.
pub fn hsl_css(hsl: &Hsl) -> String {
    format!("hsl({}, {}%, {}%)", hsl.h, hsl.s, hsl.l)
}

/// The derived palette used by the shell.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Palette {
    /// Primary colour exactly as configured.
    pub primary_main: String,
    /// Secondary colour exactly as configured.
    pub secondary_main: String,
    /// Application background.
    pub background_default: String,
    /// Sidebar/paper background.
    pub background_paper: String,
    /// Divider/border colour.
    pub divider: String,
    /// Primary text colour.
    pub text_primary: String,
    /// Secondary text colour.
    pub text_secondary: String,
    /// Disabled text colour.
    pub text_disabled: String,
    /// Active navigation fill.
    pub primary_bg: String,
    /// Active navigation hover fill.
    pub primary_bg_hover: String,
    /// Active navigation foreground.
    pub primary_text: String,
    /// Primary border colour.
    pub primary_border: String,
}

/// Derive the palette for a primary/secondary pair and light/dark mode.
///
/// The background, divider and text formulas mirror `createMuiTheme`; the
/// primary aliases mirror `applyTheme`.
pub fn derive_palette(primary_hex: &str, secondary_hex: &str, dark: bool) -> Palette {
    let secondary = hex_to_hsl(secondary_hex);
    let (sh, ss) = (secondary.h, secondary.s);

    let background_default = if dark {
        hsl_css(&Hsl {
            h: sh,
            s: ss.min(25),
            l: 7,
        })
    } else {
        hsl_css(&Hsl {
            h: sh,
            s: ss.min(20),
            l: 94,
        })
    };
    let background_paper = if dark {
        hsl_css(&Hsl {
            h: sh,
            s: ss.min(20),
            l: 12,
        })
    } else {
        "#ffffff".to_string()
    };
    let divider = if dark {
        hsl_css(&Hsl {
            h: sh,
            s: ss.min(18),
            l: 22,
        })
    } else {
        hsl_css(&Hsl {
            h: sh,
            s: ss.min(18),
            l: 82,
        })
    };
    let text_primary = if dark {
        hsl_css(&Hsl {
            h: sh,
            s: 10,
            l: 92,
        })
    } else {
        hsl_css(&Hsl {
            h: sh,
            s: 12,
            l: 18,
        })
    };
    let text_secondary = if dark {
        hsl_css(&Hsl { h: sh, s: 8, l: 68 })
    } else {
        hsl_css(&Hsl {
            h: sh,
            s: 10,
            l: 48,
        })
    };
    let text_disabled = if dark {
        hsl_css(&Hsl { h: sh, s: 6, l: 38 })
    } else {
        hsl_css(&Hsl { h: sh, s: 8, l: 68 })
    };

    let shades = derive_shades(primary_hex);
    let shade = |step: u16| {
        shades
            .get(&step)
            .copied()
            .unwrap_or(Hsl { h: 0, s: 0, l: 0 })
    };
    let primary_bg = hsl_css(&shade(if dark { 900 } else { 50 }));
    let primary_bg_hover = hsl_css(&shade(if dark { 800 } else { 100 }));
    let primary_text = hsl_css(&shade(if dark { 300 } else { 600 }));
    let primary_border = hsl_css(&shade(if dark { 800 } else { 200 }));

    Palette {
        primary_main: primary_hex.to_string(),
        secondary_main: secondary_hex.to_string(),
        background_default,
        background_paper,
        divider,
        text_primary,
        text_secondary,
        text_disabled,
        primary_bg,
        primary_bg_hover,
        primary_text,
        primary_border,
    }
}

/// Resolve the base font size, defaulting to 16 px for absent/invalid values.
pub fn base_font_size(font_size: Option<f32>) -> f32 {
    match font_size {
        Some(size) if size > 0.0 => size,
        _ => 16.0,
    }
}

/// The shipped font stack starts with Inter.
pub const FONT_FAMILY: &str = "Inter";
/// Button corner radius from the shipped MUI theme.
pub const RADIUS_BUTTON: f32 = 8.0;
/// Popover corner radius.
pub const RADIUS_POPOVER: f32 = 8.0;
/// Dialog corner radius.
pub const RADIUS_DIALOG: f32 = 12.0;
/// Shipped button font weight.
pub const BUTTON_FONT_WEIGHT: u16 = 500;
/// Shipped button text transform (none).
pub const BUTTON_TEXT_TRANSFORM_NONE: bool = true;

/// MUI default error palette.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ErrorColors {
    /// `error.main`.
    pub main: &'static str,
    /// `error.light`.
    pub light: &'static str,
    /// `error.dark`.
    pub dark: &'static str,
}

/// MUI defaults for the error palette.
pub const ERROR_COLORS: ErrorColors = ErrorColors {
    main: "#d32f2f",
    light: "#ef5350",
    dark: "#c62828",
};

/// Theme configuration accepted by [`apply_to_kit`].
#[derive(Clone, Debug, PartialEq)]
pub struct ThemeConfig {
    /// Primary/accent colour as a hex string.
    pub primary_hex: String,
    /// Secondary colour as a hex string.
    pub secondary_hex: String,
    /// Whether to use the dark palette.
    pub dark: bool,
    /// Optional base font size; absent/invalid values resolve to 16.
    pub font_size: Option<f32>,
}

impl Default for ThemeConfig {
    fn default() -> Self {
        // The gpui shell prototype's shipped defaults; the React store keeps
        // the same primary/secondary pair in its config.
        Self {
            primary_hex: "#f0883e".to_string(),
            secondary_hex: "#3a2418".to_string(),
            dark: true,
            font_size: None,
        }
    }
}

/// Whether `value` is a `#rgb` or `#rrggbb` hex colour.
pub fn is_hex_color(value: &str) -> bool {
    let Some(hex) = value.strip_prefix('#') else {
        return false;
    };
    matches!(hex.len(), 3 | 6) && hex.chars().all(|c| c.is_ascii_hexdigit())
}

impl ThemeConfig {
    /// Build a theme configuration from persisted settings.
    ///
    /// Invalid hex colours fall back to [`ThemeConfig::default`]'s values and a
    /// zero font size resolves to the shipped 16 px default, so a corrupt
    /// config cannot panic or produce a black palette.
    pub fn from_settings(settings: &stratum_app::settings::ThemeSettingsDto) -> Self {
        let fallback = Self::default();
        Self {
            primary_hex: if is_hex_color(&settings.primary_color) {
                settings.primary_color.clone()
            } else {
                fallback.primary_hex
            },
            secondary_hex: if is_hex_color(&settings.secondary_color) {
                settings.secondary_color.clone()
            } else {
                fallback.secondary_hex
            },
            dark: settings.dark_mode,
            font_size: (settings.font_size > 0).then_some(settings.font_size as f32),
        }
    }

    /// Derive the palette for this configuration.
    pub fn palette(&self) -> Palette {
        derive_palette(&self.primary_hex, &self.secondary_hex, self.dark)
    }

    /// Convert a CSS colour (`hsl(...)` or `#rrggbb`) into a gpui colour.
    pub fn to_hsla(&self, css: &str) -> gpui::Hsla {
        if let Some(hex) = css.strip_prefix('#') {
            let value = u32::from_str_radix(hex, 16).unwrap_or(0);
            return gpui::rgb(value).into();
        }
        if let Some(hsl) = parse_hsl_css(css) {
            return gpui::hsla(
                hsl.h as f32 / 360.0,
                hsl.s as f32 / 100.0,
                hsl.l as f32 / 100.0,
                1.0,
            );
        }
        gpui::rgb(0x000000).into()
    }
}

/// Parse the `hsl(h, s%, l%)` form emitted by [`hsl_css`].
pub fn parse_hsl_css(css: &str) -> Option<Hsl> {
    let inner = css.strip_prefix("hsl(")?.strip_suffix(')')?;
    let mut parts = inner.split(',');
    let h = parts.next()?.trim().parse::<i32>().ok()?;
    let s = parts
        .next()?
        .trim()
        .strip_suffix('%')?
        .trim()
        .parse::<i32>()
        .ok()?;
    let l = parts
        .next()?
        .trim()
        .strip_suffix('%')?
        .trim()
        .parse::<i32>()
        .ok()?;
    if parts.next().is_some() {
        return None;
    }
    Some(Hsl { h, s, l })
}

/// Apply the derived palette to gpui-kit's global theme.
///
/// The mapping is the shell parity contract: primary drives navigation and
/// focus, `accent` is the active-row fill, `secondary` is the sidebar paper,
/// and the error token uses MUI's default red.
pub fn apply_to_kit(cx: &mut gpui::App, cfg: &ThemeConfig) {
    let palette = cfg.palette();
    let mode = if cfg.dark {
        ThemeMode::Dark
    } else {
        ThemeMode::Light
    };
    Theme::change(mode, None, cx);
    let theme = Theme::global_mut(cx);
    theme.colors.primary = cfg.to_hsla(&palette.primary_main);
    theme.colors.accent = cfg.to_hsla(&palette.primary_bg);
    theme.colors.accent_foreground = cfg.to_hsla(&palette.primary_text);
    theme.colors.background = cfg.to_hsla(&palette.background_default);
    theme.colors.secondary = cfg.to_hsla(&palette.background_paper);
    theme.colors.border = cfg.to_hsla(&palette.divider);
    theme.colors.foreground = cfg.to_hsla(&palette.text_primary);
    theme.colors.muted_foreground = cfg.to_hsla(&palette.text_secondary);
    theme.colors.danger = cfg.to_hsla(ERROR_COLORS.main);
    theme.font_family = FONT_FAMILY.into();
    theme.font_size = px(base_font_size(cfg.font_size));
    theme.radius = px(RADIUS_BUTTON);
    theme.radius_lg = px(RADIUS_DIALOG);
}

#[cfg(test)]
mod tests {
    use super::*;
    use ::core::prelude::v1::test;

    #[test]
    fn from_settings_keeps_valid_values() {
        let settings = stratum_app::settings::ThemeSettingsDto {
            dark_mode: false,
            primary_color: "#f97316".to_string(),
            secondary_color: "#6b7280".to_string(),
            font_size: 18,
        };
        let config = ThemeConfig::from_settings(&settings);
        assert_eq!(config.primary_hex, "#f97316");
        assert_eq!(config.secondary_hex, "#6b7280");
        assert!(!config.dark);
        assert_eq!(config.font_size, Some(18.0));
    }

    #[test]
    fn from_settings_falls_back_on_invalid_hex_and_zero_font_size() {
        let settings = stratum_app::settings::ThemeSettingsDto {
            dark_mode: true,
            primary_color: "orange".to_string(),
            secondary_color: "#12".to_string(),
            font_size: 0,
        };
        let config = ThemeConfig::from_settings(&settings);
        let fallback = ThemeConfig::default();
        assert_eq!(config.primary_hex, fallback.primary_hex);
        assert_eq!(config.secondary_hex, fallback.secondary_hex);
        assert_eq!(config.font_size, None);
        assert!(config.dark);
    }
}
