//! Pure image helpers for asset thumbnails and upload compression.
//!
//! This module mirrors the shipped React attachment behaviour
//! (`panels/editor/asset_actions.rs`, `panels/editor/attachments.rs`) in Rust so
//! the native shell can share the exact same upload policy. The `image` crate
//! (MIT/Apache-2.0, already present transitively) is the decoder used for both
//! thumbnails and compression; only raster formats are decodable.
//!
//! Everything here is pure: no filesystem or database access, so the helpers
//! are fully unit-testable. The service methods in [`super`] read/write assets
//! and delegate to these functions.

use image::DynamicImage;

/// Maximum upload size in bytes. Matches `ASSET_MAX_BYTES` in
/// `src/lib/assetUpload.ts` (8 MiB).
pub const ASSET_MAX_BYTES: usize = 8 * 1024 * 1024;

/// Maximum edge length an oversized image is downscaled to before JPEG
/// re-encoding, matching the React `compressImage` canvas limit (2048 px).
pub const IMAGE_COMPRESS_MAX_EDGE: u32 = 2048;

/// JPEG quality used for oversized-image uploads, matching the React
/// `canvas.toBlob(..., 'image/jpeg', 0.85)` call.
pub const IMAGE_JPEG_QUALITY: u8 = 85;

/// Maximum edge length for attachment thumbnails generated by the native shell.
pub const THUMBNAIL_MAX_EDGE: u32 = 512;

/// A generated thumbnail: PNG bytes plus the scaled pixel dimensions.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ThumbnailImage {
    /// Encoded PNG bytes of the thumbnail.
    pub png: Vec<u8>,
    /// Thumbnail width in pixels.
    pub width: u32,
    /// Thumbnail height in pixels.
    pub height: u32,
}

/// Compute scaled dimensions that fit within `max_edge` while preserving the
/// aspect ratio. Returns the input dimensions unchanged when the image already
/// fits (never upscales).
fn scaled_dimensions(width: u32, height: u32, max_edge: u32) -> (u32, u32) {
    let edge = width.max(height);
    if edge <= max_edge {
        return (width, height);
    }
    // The longer edge maps exactly onto `max_edge`; the shorter edge follows the
    // same factor and is clamped to at least one pixel so degenerate aspect
    // ratios cannot produce a zero-sized image.
    let scale = max_edge as f64 / edge as f64;
    let scaled_width = ((width as f64 * scale).round() as u32).clamp(1, max_edge);
    let scaled_height = ((height as f64 * scale).round() as u32).clamp(1, max_edge);
    (scaled_width, scaled_height)
}

/// Decode an image and produce a PNG thumbnail no larger than `max_edge`.
///
/// The image is downscaled preserving aspect ratio and is never upscaled. The
/// returned [`ThumbnailImage`] carries the encoded PNG bytes and the scaled
/// dimensions.
///
/// # Errors
///
/// Returns a human-readable message when `bytes` is empty, `max_edge` is zero,
/// the bytes are not a decodable raster image (SVG is not decodable here), or
/// PNG encoding fails.
pub fn thumbnail_for_image(bytes: &[u8], max_edge: u32) -> Result<ThumbnailImage, String> {
    if bytes.is_empty() {
        return Err("thumbnail: empty image data".to_string());
    }
    if max_edge == 0 {
        return Err("thumbnail: max_edge must be greater than zero".to_string());
    }

    let decoded = decode_image(bytes)?;
    let (width, height) = scaled_dimensions(decoded.width(), decoded.height(), max_edge);
    let scaled = if (width, height) == (decoded.width(), decoded.height()) {
        decoded
    } else {
        decoded.resize_exact(width, height, image::imageops::FilterType::Lanczos3)
    };

    let mut png = Vec::new();
    scaled
        .write_with_encoder(image::codecs::png::PngEncoder::new(&mut png))
        .map_err(|e| format!("thumbnail: encode PNG: {e}"))?;

    Ok(ThumbnailImage {
        png,
        width: scaled.width(),
        height: scaled.height(),
    })
}

/// Compress an oversized image for upload, mirroring React `compressImage`.
///
/// The image is downscaled to [`IMAGE_COMPRESS_MAX_EDGE`] and re-encoded as a
/// JPEG at [`IMAGE_JPEG_QUALITY`]. Returns `Some(jpeg_bytes)` only when the
/// re-encoded result is strictly smaller than the input; `None` means the
/// caller must keep the original bytes (React resolves the original `File` in
/// that case).
///
/// # Errors
///
/// Returns a human-readable message when `bytes` is empty or cannot be decoded
/// as a raster image. Callers that treat compression as best-effort (for
/// example [`prepare_upload`]) fall back to the original bytes.
pub fn compress_image_for_upload(bytes: &[u8]) -> Result<Option<Vec<u8>>, String> {
    if bytes.is_empty() {
        return Err("compress: empty image data".to_string());
    }

    let decoded = decode_image(bytes)?;
    let (width, height) =
        scaled_dimensions(decoded.width(), decoded.height(), IMAGE_COMPRESS_MAX_EDGE);
    let scaled = if (width, height) == (decoded.width(), decoded.height()) {
        decoded
    } else {
        decoded.resize_exact(width, height, image::imageops::FilterType::Lanczos3)
    };

    let mut jpeg = Vec::new();
    // `write_with_encoder` drops the alpha channel automatically for formats
    // such as RGBA that JPEG cannot represent.
    scaled
        .write_with_encoder(image::codecs::jpeg::JpegEncoder::new_with_quality(
            &mut jpeg,
            IMAGE_JPEG_QUALITY,
        ))
        .map_err(|e| format!("compress: encode JPEG: {e}"))?;

    if jpeg.len() < bytes.len() {
        Ok(Some(jpeg))
    } else {
        Ok(None)
    }
}

/// Apply the single upload size policy shared by every import entry point.
///
/// This mirrors `assetFileToBase64` in `src/lib/assetUpload.ts`:
/// - at or below [`ASSET_MAX_BYTES`] the bytes and MIME are returned unchanged;
/// - above the limit an image MIME is compressed via
///   [`compress_image_for_upload`] and returned as `image/jpeg`; if compression
///   fails or produces nothing smaller, the original bytes and MIME are kept;
/// - above the limit a non-image is rejected with the exact sentinel
///   `"file_too_large"` (translated by the UI).
///
/// # Errors
///
/// Returns `Err("file_too_large")` for oversized non-image payloads.
pub fn prepare_upload(bytes: Vec<u8>, mime: &str) -> Result<(Vec<u8>, String), String> {
    if bytes.len() <= ASSET_MAX_BYTES {
        return Ok((bytes, mime.to_string()));
    }
    if pkm_block::assets::is_image_mime(mime) {
        return match compress_image_for_upload(&bytes) {
            Ok(Some(compressed)) => Ok((compressed, "image/jpeg".to_string())),
            // Not smaller, or not decodable: keep the original payload and MIME.
            Ok(None) | Err(_) => Ok((bytes, mime.to_string())),
        };
    }
    Err("file_too_large".to_string())
}

/// Decode raster image bytes with format auto-detection.
fn decode_image(bytes: &[u8]) -> Result<DynamicImage, String> {
    image::load_from_memory(bytes).map_err(|e| format!("decode image: {e}"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use image::{ImageBuffer, Rgba, RgbaImage};

    /// Encode an RGBA image as PNG bytes.
    fn png_bytes(image: &RgbaImage) -> Vec<u8> {
        let mut out = Vec::new();
        image
            .write_with_encoder(image::codecs::png::PngEncoder::new(&mut out))
            .unwrap();
        out
    }

    /// Build a deterministic RGBA test image filled by `pixel`.
    fn image_with(width: u32, height: u32, pixel: impl Fn(u32, u32) -> [u8; 4]) -> RgbaImage {
        ImageBuffer::<Rgba<u8>, _>::from_fn(width, height, |x, y| Rgba(pixel(x, y)))
    }

    #[test]
    fn thumbnail_scales_down_preserving_aspect_ratio() {
        let image = image_with(64, 32, |x, y| [x as u8, y as u8, 128, 255]);
        let source = png_bytes(&image);

        let thumb = thumbnail_for_image(&source, 16).unwrap();
        assert_eq!((thumb.width, thumb.height), (16, 8));
        // The returned PNG must decode and match the reported dimensions.
        let decoded = image::load_from_memory(&thumb.png).unwrap();
        assert_eq!((decoded.width(), decoded.height()), (16, 8));
    }

    #[test]
    fn thumbnail_never_upscales() {
        let image = image_with(64, 32, |x, y| [x as u8, y as u8, 64, 255]);
        let source = png_bytes(&image);

        let thumb = thumbnail_for_image(&source, 100).unwrap();
        assert_eq!((thumb.width, thumb.height), (64, 32));
    }

    #[test]
    fn thumbnail_rejects_invalid_input() {
        assert!(thumbnail_for_image(&[], 16).is_err());
        assert!(thumbnail_for_image(b"not an image", 16).is_err());
        let image = image_with(8, 8, |_, _| [0, 0, 0, 255]);
        let source = png_bytes(&image);
        assert!(thumbnail_for_image(&source, 0).is_err());
    }

    #[test]
    fn scaled_dimensions_handles_degenerate_aspect_ratio() {
        // A very wide image keeps its longer edge within the limit and never
        // collapses the shorter edge to zero.
        assert_eq!(scaled_dimensions(1000, 1, 16), (16, 1));
        assert_eq!(scaled_dimensions(1, 1000, 16), (1, 16));
        // Fits unchanged.
        assert_eq!(scaled_dimensions(16, 16, 16), (16, 16));
    }

    #[test]
    fn compress_returns_smaller_jpeg_for_noise_image() {
        // Deterministic noise so the PNG cannot compress well.
        let image = image_with(512, 512, |x, y| {
            let v = (x.wrapping_mul(31) ^ y.wrapping_mul(17)) as u8;
            [v, v.wrapping_add(7), v.wrapping_add(13), 255]
        });
        let source = png_bytes(&image);

        let compressed = compress_image_for_upload(&source).unwrap();
        let jpeg = compressed.expect("noise image must shrink as JPEG");
        assert!(jpeg.len() < source.len());
        // JPEG magic bytes.
        assert_eq!(&jpeg[..2], &[0xFF, 0xD8]);
    }

    #[test]
    fn compress_keeps_tiny_image_unchanged_when_not_smaller() {
        // A single flat pixel PNG is already smaller than any JPEG.
        let image = image_with(1, 1, |_, _| [0, 0, 0, 255]);
        let source = png_bytes(&image);
        assert!(compress_image_for_upload(&source).unwrap().is_none());
    }

    #[test]
    fn compress_rejects_invalid_input() {
        assert!(compress_image_for_upload(&[]).is_err());
        assert!(compress_image_for_upload(b"nope").is_err());
    }

    #[test]
    fn prepare_upload_boundary_exactly_at_limit_is_unchanged() {
        let bytes = vec![7u8; ASSET_MAX_BYTES];
        let (out, mime) = prepare_upload(bytes.clone(), "application/octet-stream").unwrap();
        assert_eq!(out.len(), ASSET_MAX_BYTES);
        assert_eq!(out, bytes);
        assert_eq!(mime, "application/octet-stream");
    }

    #[test]
    fn prepare_upload_boundary_one_byte_over_rejects_non_image() {
        let bytes = vec![7u8; ASSET_MAX_BYTES + 1];
        let err = prepare_upload(bytes, "application/pdf").unwrap_err();
        assert_eq!(err, "file_too_large");
    }

    #[test]
    fn prepare_upload_falls_back_for_oversized_undecodable_image() {
        // Oversized image MIME that is not decodable: keep original bytes + MIME.
        let bytes = vec![0u8; ASSET_MAX_BYTES + 1];
        let (out, mime) = prepare_upload(bytes.clone(), "image/png").unwrap();
        assert_eq!(out, bytes);
        assert_eq!(mime, "image/png");
    }

    #[test]
    fn prepare_upload_compresses_oversized_image() {
        let image = image_with(2200, 2200, |x, y| {
            let v = (x.wrapping_mul(31) ^ y.wrapping_mul(17)) as u8;
            [v, v.wrapping_add(7), v.wrapping_add(13), 255]
        });
        let source = png_bytes(&image);
        assert!(source.len() > ASSET_MAX_BYTES, "fixture must be oversized");

        let (out, mime) = prepare_upload(source.clone(), "image/png").unwrap();
        assert_eq!(mime, "image/jpeg");
        assert!(out.len() < source.len());
        assert!(out.len() <= ASSET_MAX_BYTES);
    }
}
